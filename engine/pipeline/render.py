#!/usr/bin/env python3
"""Stage 6 - visuals (Remotion render).

Writes remotion/src/generated/props.json from script.json + timing.json + calc.json, copies the
narration into remotion/public/<video>/, then renders with the Remotion CLI.

Modes:
  --mode full      1920x1080, full length                      -> renders/<id>_1080p.mp4
  --mode low       960x540 (--scale 0.5), full length           -> renders/<id>_540p.mp4
  --mode preview   1920x1080, first --seconds (default 90)      -> renders/<id>_preview<N>s_1080p.mp4
  --stills         one PNG per scene run (QA contact sheet)     -> renders/stills/
Self-checks: ffprobe duration matches timing.json (+-0.5 s), resolution, an audio stream when narration
exists, and ffmpeg blackdetect finds no black stretch > 2 s.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess

from lib import REMOTION, fail, get_stage, log, read_json, require, set_stage, video_dir, write_json

STAGE = "render"


def build_props(vdir, vid):
    script = read_json(vdir / "script.json")
    timing = read_json(vdir / "timing.json")
    calc = read_json(vdir / "calc.json")
    has_audio = timing["provider"] != "silent"
    pub = REMOTION / "public" / vid
    pub.mkdir(parents=True, exist_ok=True)
    vscenes = REMOTION / "src" / "videos" / vid / "scenes.tsx"
    if not vscenes.exists():
        raise SystemExit(f"[render] missing {vscenes} (export const SCENES: Record<string, SceneEntry> = {{...}})")
    keys = set(re.findall(r"^\s+(\w+): \{ C:", (REMOTION / "src" / "scenes" / "shared.tsx").read_text(), re.M))
    keys |= set(re.findall(r"^\s+(\w+): \{ C:", vscenes.read_text(), re.M))
    missing = sorted({b["visual"]["scene"] for s in script["sections"] for b in s["beats"]} - keys)
    if missing:
        raise SystemExit(f"[render] scenes used in script.json but not registered: {missing}")
    gen = REMOTION / "src" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "registry.ts").write_text(
        "// GENERATED by pipeline/render.py - selects the per-video scene registry\n"
        f'export {{ SCENES as VIDEO_SCENES }} from "../videos/{vid}/scenes";\n', encoding="utf-8")
    research = read_json(vdir / "research.json")
    src_names = []
    for k in sorted(research["sources"], key=lambda x: int(x[1:])):
        name = re.sub(r"\s*\([^)]*\)", "", research["sources"][k]["title"]).split(",")[0].strip()
        if name not in src_names:
            src_names.append(name)
    props = {
        "videoId": vid, "title": script["title"], "nextVideo": script["next_video"],
        "hasAudio": has_audio, "audioFile": f"{vid}/narration.wav",
        "sections": [{"id": s["id"], "chapter": s["chapter"], "clock": s.get("clock"),
                      "beats": [{k: b.get(k) for k in ("id", "text", "kinetic", "card", "retention", "visual")}
                                for b in s["beats"]]} for s in script["sections"]],
        "timing": {"total": timing["total"], "beats": timing["beats"], "sections": timing["sections"]},
        "cards": calc["cards"],
        "values": {k: {"value": v["value"], "display": v["display"], "unit": v["unit"]} for k, v in calc["values"].items()},
        "extra": calc.get("extra", {}),
        "sources": src_names,
    }
    if has_audio:
        shutil.copy(vdir / "audio" / "narration.wav", pub / "narration.wav")
    write_json(REMOTION / "src" / "generated" / "props.json", props)
    return props


def run(cmd):
    log(STAGE, " ".join(cmd))
    p = subprocess.run(cmd, cwd=REMOTION, text=True, capture_output=True)
    tail = "\n".join((p.stdout + p.stderr).strip().splitlines()[-15:])
    if p.returncode:
        raise RuntimeError(tail)
    return tail


def probe(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_type,width,height",
                          "-of", "json", str(path)], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def black_stretches(path, scale):
    p = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-vf", f"scale=320:-2,blackdetect=d=2:pix_th=0.05",
                        "-an", "-f", "null", "-"], capture_output=True, text=True)
    return re.findall(r"black_start:([\d.]+) black_end:([\d.]+)", p.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("video_id", nargs="?", default="earth-stops-1s")
    ap.add_argument("--mode", choices=["full", "low", "preview"], default="low")
    ap.add_argument("--seconds", type=int, default=90)
    ap.add_argument("--stills", action="store_true")
    ap.add_argument("--concurrency", default=os.environ.get("REMOTION_CONCURRENCY", "4"))
    a = ap.parse_args()
    vdir = video_dir(a.video_id)
    require(vdir, "factcheck", "voice")
    props = build_props(vdir, a.video_id)
    out_dir = vdir / "renders"
    out_dir.mkdir(exist_ok=True)
    fps = 30
    total = props["timing"]["total"]

    if a.stills:
        sd = out_dir / "stills"
        sd.mkdir(exist_ok=True)
        # one frame in the middle of every beat window
        tb = props["timing"]["beats"]
        frames = sorted({int(((b["start"] + b["end"]) / 2) * fps) for b in tb})
        run(["npx", "remotion", "render", "IfEngineVideo", str(sd / "f"), f"--frames={','.join(map(str, frames))}",
             "--image-format=png", "--sequence", f"--concurrency={a.concurrency}", "--scale=0.5"])
        # contact sheets (12 frames each) for visual QA
        from PIL import Image, ImageDraw
        pngs = sorted((sd / "f").glob("*.png"))
        for k in range(0, len(pngs), 12):
            sheet = Image.new("RGB", (4 * 480, 3 * 270), "black")
            for j, pth in enumerate(pngs[k:k + 12]):
                im = Image.open(pth).convert("RGB").resize((480, 270))
                ImageDraw.Draw(im).text((8, 250), pth.stem.split("-")[-1], fill="yellow")
                sheet.paste(im, ((j % 4) * 480, (j // 4) * 270))
            sheet.save(sd / f"sheet_{k // 12 + 1:02d}.png")
        log(STAGE, f"stills -> {sd} ({len(frames)} frames, {len(range(0, len(pngs), 12))} contact sheets)")
        return

    if a.mode == "full":
        out, extra, exp_w = out_dir / f"{a.video_id}_1080p.mp4", ["--crf=20"], 1920
    elif a.mode == "low":
        out, extra, exp_w = out_dir / f"{a.video_id}_540p.mp4", ["--scale=0.5", "--crf=23"], 960
    else:
        out = out_dir / f"{a.video_id}_preview{a.seconds}s_1080p.mp4"
        extra, exp_w = ["--crf=20", f"--frames=0-{a.seconds * fps - 1}"], 1920
    try:
        run(["npx", "remotion", "render", "IfEngineVideo", str(out), "--codec=h264", "--audio-codec=aac",
             "--audio-bitrate=192k", f"--concurrency={a.concurrency}", "--log=error", *extra])
    except RuntimeError as e:
        fail(vdir, STAGE, f"remotion render failed ({a.mode}): {e}")

    info = probe(out)
    dur = float(info["format"]["duration"])
    vstreams = [s for s in info["streams"] if s["codec_type"] == "video"]
    has_a = any(s["codec_type"] == "audio" for s in info["streams"])
    exp_dur = a.seconds if a.mode == "preview" else total
    problems = []
    if abs(dur - exp_dur) > 0.6:
        problems.append(f"duration {dur:.2f}s != expected {exp_dur:.2f}s")
    if vstreams[0]["width"] != exp_w:
        problems.append(f"width {vstreams[0]['width']} != {exp_w}")
    if props["hasAudio"] and not has_a:
        problems.append("no audio stream")
    blacks = black_stretches(out, 320)
    if blacks:
        problems.append(f"black stretches: {blacks[:3]}")
    renders = dict(get_stage(vdir, STAGE).get("renders", {}))
    renders[a.mode] = {"file": str(out.relative_to(vdir)), "duration_s": round(dur, 2),
                       "resolution": f"{vstreams[0]['width']}x{vstreams[0]['height']}", "audio": has_a,
                       "size_mb": round(out.stat().st_size / 1e6, 1), "problems": problems}
    status = "failed" if problems else ("done" if props["hasAudio"] else "degraded")
    set_stage(vdir, STAGE, status, renders=renders,
              note=None if props["hasAudio"] else "rendered without narration (no TTS available)")
    if problems:
        fail(vdir, STAGE, "; ".join(problems), renders=renders)
    log(STAGE, f"OK {a.mode}: {out} {dur:.1f}s {vstreams[0]['width']}x{vstreams[0]['height']} audio={has_a}")


if __name__ == "__main__":
    main()
