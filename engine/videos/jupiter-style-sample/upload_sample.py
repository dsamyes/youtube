#!/usr/bin/env python3
"""Upload the style sample to YouTube as PRIVATE (owner review only). No playlist, no subscriber
notification, no thumbnail/captions, never public: this is a look-and-pacing test, not an episode.

  python -B engine/videos/jupiter-style-sample/upload_sample.py [--file renders/...mp4] [--dry-run]

Reuses pipeline/upload.py (OAuth client from engine/secrets, resumable upload with retries) without
changing it. Writes build/upload.json with the YouTube id.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "pipeline"))

SID = "jupiter-style-sample"


def description(credits: list[dict], stats: dict) -> str:
    lines = [
        "PRIVATE STYLE SAMPLE for The If Engine (not a published episode).",
        f"Built {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC by the automated pipeline: NASA footage + our 3D, "
        f"{stats.get('shots', '?')} shots, average shot {stats.get('avg_shot_s', '?')} s.",
        "",
        "Footage and credits:",
    ]
    for c in credits:
        if c.get("provider") in ("kokoro", "pipeline/sound.py", "engine 3D library"):
            continue
        page = f" {c['page']}" if c.get("page") else ""
        lines.append(f"- {c.get('title') or c.get('id')}: {c.get('credit', '')}.{page}")
    lines += ["", "Voice: Kokoro-82M (Apache-2.0), voice am_michael. Music and sound effects: generated by The If Engine.",
              "NASA material is used under NASA's media guidelines and does not imply NASA endorsement."]
    return "\n".join(lines)[:4900]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", default=str(HERE / "renders" / f"{SID}_1080p.mp4"))
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    video = Path(a.file)
    if not video.exists() or video.read_bytes()[4:8] != b"ftyp":
        sys.exit(f"[upload-sample] {video} missing or not an MP4")
    credits = json.loads((HERE / "build" / "credits.json").read_text()) if (HERE / "build" / "credits.json").exists() else []
    qa = HERE / "build" / "qa" / "summary.json"
    stats = json.loads(qa.read_text()) if qa.exists() else {}
    body = {
        "snippet": {"title": "[SAMPLE] What If You Fell Into Jupiter? - new style test", "description": description(credits, stats),
                    "tags": ["The If Engine", "style sample"], "categoryId": "28", "defaultLanguage": "en", "defaultAudioLanguage": "en"},
        "status": {"privacyStatus": "private", "selfDeclaredMadeForKids": False, "containsSyntheticMedia": True,
                   "license": "youtube", "embeddable": False},
    }
    if a.dry_run:
        print(json.dumps(body, indent=1, ensure_ascii=False))
        return
    from googleapiclient.http import MediaFileUpload
    from upload import resumable, youtube_client
    yt = youtube_client()
    media = MediaFileUpload(str(video), mimetype="video/mp4", chunksize=8 * 1024 * 1024, resumable=True)
    res = resumable(yt.videos().insert(part="snippet,status", body=body, media_body=media, notifySubscribers=False), "sample")
    vid = res["id"]
    status = res.get("status", {}).get("privacyStatus")
    if status != "private":
        sys.exit(f"[upload-sample] unexpected privacy {status} for {vid}")
    out = {"youtube_id": vid, "url": f"https://youtu.be/{vid}", "privacy": status,
           "uploaded": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")}
    (HERE / "build").mkdir(exist_ok=True)
    (HERE / "build" / "upload.json").write_text(json.dumps(out, indent=1))
    print(f"[upload-sample] uploaded PRIVATE: https://youtu.be/{vid}")


if __name__ == "__main__":
    main()
